public class Asterics{
  public static void main(String[] args){
  
    for (int row = 1; row <= 10; row++){
        for (int asterics = 1; asterics <= row; asterics++){
            System.out.print('*');
            }
            System.out.println();
                }
                
    for (int row = 10; row >= 1; row--){
        for (int asterics = 1; asterics <= row; asterics++){
            System.out.print('*');
            }
            System.out.println();
                }
                
    for (int row = 10; row >= 1; row--){
        for (int asterics = 1; asterics <= row; asterics++){
            System.out.print('*' + " ");
            }
            System.out.println();
                }
                
    for (int row = 1; row <= 10; row++){
        for (int asterics = 1; asterics <= row; asterics++){
            System.out.print('*' + " ");
            }
            System.out.println();
   }
  }
}
